const express = require("express");
const MasterRecordController = require("../controllers/MasterRecordController");
const controller = new MasterRecordController();
const router = express.Router({ mergeParams: true });
router.use((req, res, next) => {
  if (req.params.module === "configuration" && req.method !== "GET")
    return res
      .status(405)
      .json({
        error: { message: "Use validated configuration settings endpoints" },
      });
  next();
});
router.use((req, res, next) => {
  if (
    req.method !== "GET" &&
    ["organization", "factories", "departments", "production-lines"].includes(
      req.params.module,
    )
  )
    return res
      .status(405)
      .json({
        error: {
          message: "Use the validated organization hierarchy endpoints",
        },
      });
  next();
});
const asyncRoute = (handler) => (req, res, next) =>
  Promise.resolve(handler(req, res, next)).catch(next);
const movement = require("../controllers/MovementController");
const inspection = require("../controllers/InspectionController");
const calibration = require("../controllers/CalibrationController");
const notification = require("../controllers/NotificationController");
router.use((req, res, next) => {
  if (req.params.module !== "notifications") return next();
  if (req.method === "GET" && req.path === "/")
    return asyncRoute(notification.list.bind(notification))(req, res, next);
  const match = req.path.match(/^\/([^/]+)\/read$/);
  if (req.method === "POST" && match) {
    req.params.id = match[1];
    return asyncRoute(notification.read.bind(notification))(req, res, next);
  }
  return res
    .status(405)
    .json({
      error: { message: "Notifications are generated by maintenance events" },
    });
});
router.use((req, res, next) => {
  if (req.params.module !== "calibration") return next();
  if (req.method === "GET" && req.path === "/")
    return asyncRoute(calibration.list.bind(calibration))(req, res, next);
  if (req.method === "POST" && req.path === "/")
    return asyncRoute(calibration.create.bind(calibration))(req, res, next);
  const match = req.path.match(/^\/([^/]+)\/complete$/);
  if (req.method === "POST" && match) {
    req.params.id = match[1];
    return asyncRoute(calibration.complete.bind(calibration))(req, res, next);
  }
  return res
    .status(405)
    .json({
      error: {
        message:
          "Use calibration completion to retain certificates and history",
      },
    });
});
router.use((req, res, next) => {
  if (req.params.module !== "inspections") return next();
  if (req.method === "GET" && req.path === "/")
    return asyncRoute(inspection.list.bind(inspection))(req, res, next);
  if (req.method === "POST" && req.path === "/")
    return asyncRoute(inspection.create.bind(inspection))(req, res, next);
  const match = req.path.match(/^\/([^/]+)\/complete$/);
  if (req.method === "POST" && match) {
    req.params.id = match[1];
    return asyncRoute(inspection.complete.bind(inspection))(req, res, next);
  }
  return res
    .status(405)
    .json({
      error: {
        message:
          "Complete inspections using checklist responses; historical results cannot be deleted",
      },
    });
});
router.use((req, res, next) => {
  if (!["allocations", "transfers"].includes(req.params.module)) return next();
  const handler =
    req.method === "GET" && req.path === "/"
      ? movement.getAll
      : req.method === "POST" && req.path === "/"
        ? movement.create
        : null;
  if (handler) return asyncRoute(handler.bind(movement))(req, res, next);
  if (req.method === "PATCH" && /^\/[^/]+\/workflow$/.test(req.path))
    return next();
  return res
    .status(405)
    .json({
      error: {
        message:
          "Use movement workflow actions to preserve approval and history",
      },
    });
});
router.patch("/:id/workflow", asyncRoute(movement.transition.bind(movement)));
router.get("/", asyncRoute(controller.getAll.bind(controller)));
router.post("/", asyncRoute(controller.create.bind(controller)));
router.put("/:id", asyncRoute(controller.update.bind(controller)));
router.delete("/:id", asyncRoute(controller.delete.bind(controller)));
module.exports = router;
