module.exports = (sequelize, DataTypes) => sequelize.define('WorkOrder', {
  id: { type: DataTypes.STRING(40), primaryKey: true },
  machineId: { type: DataTypes.STRING(40), allowNull: false, field: 'machine_id' },
  organizationId: { type: DataTypes.STRING(120), field: 'organization_id' },
  factoryId: { type: DataTypes.STRING(120), field: 'factory_id' },
  issue: { type: DataTypes.STRING(255), allowNull: false },
  description: { type: DataTypes.TEXT },
  technicianName: { type: DataTypes.STRING(160), field: 'technician_name' },
  technicianId: { type: DataTypes.STRING(40), field: 'technician_id' },
  assignedBy: { type: DataTypes.STRING(160), field: 'assigned_by' },
  assignedAt: { type: DataTypes.DATE, field: 'assigned_at' },
  startedAt: { type: DataTypes.DATE, field: 'started_at' },
  pausedAt: { type: DataTypes.DATE, field: 'paused_at' },
  repairNotes: { type: DataTypes.TEXT, field: 'repair_notes' },
  diagnosis: { type: DataTypes.TEXT },
  completionNotes: { type: DataTypes.TEXT, field: 'completion_notes' },
  verificationNotes: { type: DataTypes.TEXT, field: 'verification_notes' },
  rejectionReason: { type: DataTypes.TEXT, field: 'rejection_reason' },
  verifiedBy: { type: DataTypes.STRING(160), field: 'verified_by' },
  verifiedAt: { type: DataTypes.DATE, field: 'verified_at' },
  laborMinutes: { type: DataTypes.INTEGER, field: 'labor_minutes' },
  partsCost: { type: DataTypes.DECIMAL(12, 2), field: 'parts_cost' },
  contractorCost: { type: DataTypes.DECIMAL(12, 2), field: 'contractor_cost' },
  priority: { type: DataTypes.ENUM('Critical', 'High', 'Medium', 'Low'), defaultValue: 'Medium' },
  status: { type: DataTypes.ENUM('Open', 'Assigned', 'In Progress', 'Waiting Parts', 'Repair Completed', 'Verification', 'Completed', 'Closed'), defaultValue: 'Open' },
  dueAt: { type: DataTypes.DATE, field: 'due_at' },
  completedAt: { type: DataTypes.DATE, field: 'completed_at' },
}, { tableName: 'mmms_work_orders', underscored: true });
