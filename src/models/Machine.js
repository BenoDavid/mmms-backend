module.exports = (sequelize, DataTypes) =>
  sequelize.define(
    "Machine",
    {
      id: { type: DataTypes.STRING(40), primaryKey: true },
      assetNumber: {
        type: DataTypes.STRING(80),
        allowNull: false,
        unique: true,
        field: "asset_number",
      },
      name: {
        type: DataTypes.STRING(255),
        allowNull: false,
        validate: { notEmpty: { msg: "name is required" } },
      },
      category: {
        type: DataTypes.STRING(120),
        allowNull: false,
        validate: { notEmpty: { msg: "category is required" } },
      },
      machineCode: { type: DataTypes.STRING(80), allowNull: false, unique: true, field: "machine_code" },
      description: { type: DataTypes.TEXT },
      subcategory: { type: DataTypes.STRING(120) },
      machineType: { type: DataTypes.STRING(120), field: "machine_type" },
      manufacturingYear: { type: DataTypes.INTEGER, field: "manufacturing_year" },
      brand: { type: DataTypes.STRING(120) },
      manufacturer: { type: DataTypes.STRING(120) },
      modelNumber: { type: DataTypes.STRING(120), field: "model_number" },
      serialNumber: { type: DataTypes.STRING(120), field: "serial_number" },
      factoryLocation: {
        type: DataTypes.STRING(160),
        field: "factory_location",
      },
      productionLine: { type: DataTypes.STRING(120), field: "production_line" },
      installationDate: {
        type: DataTypes.DATEONLY,
        field: "installation_date",
      },
      purchaseDate: { type: DataTypes.DATEONLY, field: "purchase_date" },
      purchaseCost: { type: DataTypes.DECIMAL(12, 2), field: "purchase_cost" },
      purchasePrice: { type: DataTypes.DECIMAL(12, 2), field: "purchase_price" },
      supplier: { type: DataTypes.STRING(180) },
      warrantyStartDate: { type: DataTypes.DATEONLY, field: "warranty_start_date" },
      warrantyExpiryDate: { type: DataTypes.DATEONLY, field: "warranty_expiry_date" },
      commissioningDate: { type: DataTypes.DATEONLY, field: "commissioning_date" },
      imageUrl: { type: DataTypes.STRING(500), field: "image_url" },
      technicalSpecifications: { type: DataTypes.JSONB, field: "technical_specifications" },
      powerConsumption: { type: DataTypes.STRING(80), field: "power_consumption" },
      machineCapacity: { type: DataTypes.STRING(120), field: "machine_capacity" },
      organizationUnit: { type: DataTypes.STRING(160), field: "organization_unit" },
      organizationId: { type: DataTypes.STRING(120), field: "organization_id" },
      factoryId: { type: DataTypes.STRING(120), field: "factory_id" },
      factory: { type: DataTypes.STRING(160) },
      department: { type: DataTypes.STRING(160) },
      floor: { type: DataTypes.STRING(120) },
      currentLocation: { type: DataTypes.STRING(180), field: "current_location" },
      responsiblePerson: { type: DataTypes.STRING(160), field: "responsible_person" },
      documents: { type: DataTypes.JSONB, defaultValue: [] },
      lifecycleStatus: { type: DataTypes.STRING(60), defaultValue: "Active", field: "lifecycle_status" },
      criticality: { type: DataTypes.STRING(30), defaultValue: "Medium" },
      lifecycleCondition: { type: DataTypes.STRING(40), defaultValue: "Operational", field: "lifecycle_condition" },
      qrReference: { type: DataTypes.STRING(120), allowNull: false, unique: true, field: "qr_reference" },
      archivedAt: { type: DataTypes.DATE, field: "archived_at" },
      status: {
        type: DataTypes.ENUM(
          "Running",
          "Idle",
          "Under Maintenance",
          "Breakdown",
          "Decommissioned",
          "Reserved",
          "Scrapped",
          "Reserved",
          "Scrapped",
        ),
        defaultValue: "Idle",
      },
      uptimePercent: {
        type: DataTypes.DECIMAL(5, 2),
        defaultValue: 0,
        field: "uptime_percent",
        validate: { min: 0, max: 100 },
      },
    },
    { tableName: "mmms_machines", underscored: true },
  );
